#!/usr/bin/env python3
"""Generate quest/host/gt4_names.inc: GT4 course label -> name and car label -> name.

usage: gen_gt4_names.py RACE_STATE CAR_LIST_MD > quest/host/gt4_names.inc
  RACE_STATE   a ps2run state of the retail game in a race (the course name table, label/name
               pointer pairs, sits in the race heap; found next to "tsukuba" "Tsukuba Circuit")
  CAR_LIST_MD  the GT Modding Hub master car list page as markdown
               (https://nenkai.github.io/gt-modding-hub/concepts/cars/master_car_list/, from GT6's
               SpecDB; its labels and names match GT4's for the GT4 cars)
"""
import re
import struct
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
import stateram  # noqa: E402


def courses(ram):
    key = ram.find(b"\0tsukuba\0Tsukuba Circuit\0")
    if key < 0:
        raise SystemExit("course table not found")
    s = key + 1
    ptr = struct.pack("<I", s)
    at = next(m.start() for m in re.finditer(re.escape(ptr), ram) if m.start() % 4 == 0)
    lo, hi = s - 0x4000, s + 0x4000
    u = lambda a: struct.unpack_from("<I", ram, a)[0]
    while lo <= u(at - 4) < hi:
        at -= 4
    ptrs = []
    while lo <= u(at) < hi:
        ptrs.append(u(at))
        at += 4
    text = lambda p: ram[p:p + 96].split(b"\0")[0].decode("utf-8")
    names = [text(p) for p in ptrs]
    return dict(zip(names[0::2], names[1::2]))


def cars(md):
    rows = re.findall(r"\|\s*(\d+)\s*\|\s*`([^`]+)`\s*\|\s*([^|]+?)\s*\|", md)
    return {label: name.replace("\\", "") for _, label, name in rows}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ram = stateram.load_ram(sys.argv[1])
    course = courses(ram)
    car = cars(open(sys.argv[2], encoding="utf-8").read())
    print("// Generated by quest/tools/gen_gt4_names.py - do not edit.")
    print("// Courses: GT4 retail (SCUS-97328) course name table. Cars: GT Modding Hub master car list.")
    print("struct NamePair { const char *label; const char *name; };")
    print("static const NamePair kCourseNames[] = {")
    for k in sorted(course):
        print(f"    {{{c_str(k)}, {c_str(course[k])}}},")
    print("};")
    print("static const NamePair kCarNames[] = {")
    for k in sorted(car):
        print(f"    {{{c_str(k)}, {c_str(car[k])}}},")
    print("};")
    print(f"// {len(course)} courses, {len(car)} cars", file=sys.stderr)


if __name__ == "__main__":
    main()
